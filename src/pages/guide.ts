export function renderGuide(root: HTMLElement): void {
  const toc = SECTIONS.map(
    (s) => `<li><a href="#guide-${s.id}" class="guide-link" data-target="guide-${s.id}">${s.title}</a></li>`,
  ).join("");
  const sections = SECTIONS.map(
    (s) => `
      <div class="card guide-section" id="guide-${s.id}">
        <h2>${s.title}</h2>
        ${s.body}
      </div>`,
  ).join("");

  root.innerHTML = `
  <style>
    .guide-toc { columns: 2; column-gap: 28px; margin: 0; padding-inline-start: 18px; }
    .guide-toc li { margin-bottom: 6px; break-inside: avoid; }
    .guide-link { color: var(--accent-dark); text-decoration: none; cursor: pointer; }
    .guide-link:hover { text-decoration: underline; }
    .guide-section h2 { margin-top: 0; color: var(--accent-dark); font-size: 19px; }
    .guide-section p { line-height: 1.9; margin: 8px 0; }
    .guide-section ul, .guide-section ol { line-height: 1.9; margin: 8px 0; padding-inline-start: 22px; }
    .guide-section li { margin-bottom: 4px; }
    .guide-tip {
      background: #fdf3e0; border: 1px solid #f0dfba; border-radius: 10px;
      padding: 10px 14px; margin: 10px 0; line-height: 1.9;
    }
  </style>
  <div class="card">
    <h2 style="margin-top: 0;">راهنمای شیرین حساب</h2>
    <p style="color: var(--muted); margin: 6px 0 12px;">آموزش قدم‌به‌قدم کار با برنامه — روی هر عنوان بزنید تا به همان بخش بروید.</p>
    <ul class="guide-toc">${toc}</ul>
  </div>
  ${sections}`;

  root.querySelectorAll<HTMLAnchorElement>(".guide-link").forEach((a) => {
    a.addEventListener("click", (ev) => {
      ev.preventDefault();
      const targetId = a.getAttribute("data-target");
      const el = targetId ? document.getElementById(targetId) : null;
      if (el) el.scrollIntoView({ behavior: "smooth", block: "start" });
    });
  });
}
